/** Returns the primary IANA timezone for a country code, or 'Asia/Kolkata' as fallback. */
export function getTimezoneForCountryCode(code: string): string {
  return COUNTRY_TIMEZONES[code?.toUpperCase()] ?? 'Asia/Kolkata';
}

/** Returns the primary IANA timezone for a country name, or 'Asia/Kolkata' as fallback. */
export function getTimezoneForCountryName(name: string): string {
  const country = getCountryByName(name);
  if (!country) return 'Asia/Kolkata';
  return getTimezoneForCountryCode(country.code);
}

