export async function detectCountryFromLocation(): Promise<Country> {
  return new Promise((resolve, reject) => {
    if (!navigator.geolocation) {
      reject(new Error('Geolocation is not supported by your browser.'));
      return;
    }

    navigator.geolocation.getCurrentPosition(
      async (position) => {
        try {
          const { latitude, longitude } = position.coords;
          // Use BigDataCloud's reverse geocoding API - highly reliable & doesn't require API key
          const res = await fetch(`https://api.bigdatacloud.net/data/reverse-geocode-client?latitude=${latitude}&longitude=${longitude}&localityLanguage=en`);
          if (!res.ok) {
            throw new Error('Reverse geocoding request failed.');
          }
          const data = await res.json();
          if (data && data.countryCode) {
            const countryObj = getCountryByCode(data.countryCode);
            if (countryObj) {
              resolve(countryObj);
              return;
            }
          }
          reject(new Error('Could not resolve country from your coordinates.'));
        } catch (err: any) {
          reject(err);
        }
      },
      (err) => {
        reject(new Error('Location permission denied or lookup failed. Please select your country manually.'));
      },
      { timeout: 10000 }
    );
  });
}
